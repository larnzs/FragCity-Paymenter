#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="${1:-$ROOT/build/extension-packages}"
MAX_UPLOAD_BYTES=$((10 * 1024 * 1024))

for command_name in zip unzip sha256sum; do
    command -v "$command_name" >/dev/null 2>&1 || {
        echo "ERROR: Required command not found: $command_name" >&2
        exit 1
    }
done

[[ -d "$ROOT/extensions" ]] || {
    echo "ERROR: extensions/ directory not found." >&2
    exit 1
}

mkdir -p "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

# Remove only package files generated by this script.
rm -f \
    "$OUT_DIR"/FragCityAPI-v*.zip \
    "$OUT_DIR"/FragCitySupportAPI-v*.zip \
    "$OUT_DIR"/FragCityCS2-v*.zip \
    "$OUT_DIR"/SHA256SUMS \
    "$OUT_DIR"/PACKAGES.txt

shopt -s nullglob
extension_count=0
package_lines=()

for type_dir in "$ROOT"/extensions/*; do
    [[ -d "$type_dir" ]] || continue
    extension_type="$(basename "$type_dir")"

    for extension_dir in "$type_dir"/*; do
        [[ -d "$extension_dir" ]] || continue

        extension_name="$(basename "$extension_dir")"
        class_file="$extension_dir/$extension_name.php"

        [[ -f "$class_file" ]] || {
            echo "ERROR: Missing main class file: $class_file" >&2
            exit 1
        }

        expected_namespace="namespace Paymenter\\Extensions\\${extension_type}\\${extension_name};"
        grep -Fq "$expected_namespace" "$class_file" || {
            echo "ERROR: Unexpected namespace in $class_file. Expected: $expected_namespace" >&2
            exit 1
        }

        grep -Eq "^[[:space:]]*class[[:space:]]+${extension_name}[[:space:]]+extends[[:space:]]+" "$class_file" || {
            echo "ERROR: Main class $extension_name was not found in $class_file." >&2
            exit 1
        }

        grep -Fq '#[ExtensionMeta(' "$class_file" || {
            echo "ERROR: $extension_name has no ExtensionMeta attribute." >&2
            exit 1
        }

        version="$(sed -nE "s/^[[:space:]]*version:[[:space:]]*'([^']+)'.*/\\1/p" "$class_file" | head -n 1)"
        [[ -n "$version" ]] || {
            echo "ERROR: Could not read ExtensionMeta version from $class_file." >&2
            exit 1
        }

        if find "$extension_dir" -type l -print -quit | grep -q .; then
            echo "ERROR: Symlinks are not allowed inside extension packages: $extension_dir" >&2
            exit 1
        fi

        archive_name="${extension_name}-v${version}.zip"
        archive_path="$TMP_DIR/$archive_name"

        # Paymenter v1.5.9 traverses only one directory below the ZIP root.
        # Therefore the archive must contain ExtensionName/ExtensionName.php,
        # not extensions/Type/ExtensionName/ExtensionName.php.
        (
            cd "$type_dir"
            zip -qr "$archive_path" "$extension_name" \
                -x "$extension_name/.DS_Store" \
                   "$extension_name/**/.DS_Store" \
                   "$extension_name/**/.git/**" \
                   "$extension_name/**/__MACOSX/**"
        )

        unzip -tq "$archive_path" >/dev/null

        roots="$(unzip -Z1 "$archive_path" | awk -F/ 'NF { print $1 }' | sort -u)"
        [[ "$roots" == "$extension_name" ]] || {
            echo "ERROR: $archive_name must contain only $extension_name/ at its root; found: $roots" >&2
            exit 1
        }

        unzip -Z1 "$archive_path" | grep -Fqx "$extension_name/$extension_name.php" || {
            echo "ERROR: Main class is not directly inside the ZIP's top-level folder." >&2
            exit 1
        }

        direct_php_files="$(unzip -Z1 "$archive_path" | awk -F/ 'NF == 2 && $2 ~ /\.php$/ { print }')"
        grep -Fqx "$extension_name/$extension_name.php" <<< "$direct_php_files" || {
            echo "ERROR: $archive_name is missing its root-level main class file." >&2
            exit 1
        }

        unexpected_php_files="$(printf '%s\n' "$direct_php_files" | grep -Fvx "$extension_name/$extension_name.php" | grep -Fvx "$extension_name/routes.php" || true)"
        [[ -z "$unexpected_php_files" ]] || {
            echo "ERROR: Unexpected root-level PHP files in $archive_name: $unexpected_php_files" >&2
            exit 1
        }

        archive_size="$(wc -c < "$archive_path" | tr -d '[:space:]')"
        (( archive_size <= MAX_UPLOAD_BYTES )) || {
            echo "ERROR: $archive_name exceeds Paymenter's 10 MiB upload limit." >&2
            exit 1
        }

        mv "$archive_path" "$OUT_DIR/$archive_name"
        package_lines+=("$extension_type | $extension_name | $version | $archive_name")
        extension_count=$((extension_count + 1))
        echo "PACKAGED: $extension_type/$extension_name ($version) -> $archive_name"
    done
done

(( extension_count > 0 )) || {
    echo "ERROR: No Paymenter extensions were found." >&2
    exit 1
}

(
    cd "$OUT_DIR"
    sha256sum ./*.zip > SHA256SUMS
)

{
    echo "FragCity Paymenter extension packages"
    echo "Paymenter compatibility: v1.5.9"
    echo "Source branch: ${GITHUB_REF_NAME:-$(git -C "$ROOT" branch --show-current 2>/dev/null || echo unknown)}"
    echo "Source commit: $(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
    echo
    printf '%s\n' "${package_lines[@]}"
    echo
    echo "Upload each extension ZIP separately in Paymenter."
    echo "Do not upload the outer GitHub Actions artifact ZIP."
} > "$OUT_DIR/PACKAGES.txt"

echo
echo "SUCCESS: Built $extension_count independently uploadable extension package(s)."
echo "Output: $OUT_DIR"
echo "Checksums: $OUT_DIR/SHA256SUMS"
